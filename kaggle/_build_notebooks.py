def main():
    base = os.path.dirname(os.path.abspath(__file__))
    builders = {
        "montage_pipeline.ipynb":    build_montage_pipeline,
        "whisper_transcribe.ipynb": build_whisper_transcribe,
        "sdxl_generate.ipynb":      build_sdxl_generate,
        "rvm_background.ipynb":      build_rvm_background,
    }
    summary = []
    for fname, builder in builders.items():
        nb = builder()
        path = os.path.join(base, fname)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(nb, f, ensure_ascii=False, indent=1)
            f.write("\n")
        # Validate by re-loading
        with open(path, "r", encoding="utf-8") as f:
            reloaded = json.load(f)
        assert reloaded["nbformat"] == 4
        n_cells = len(reloaded["cells"])
        n_md = sum(1 for c in reloaded["cells"] if c["cell_type"] == "markdown")
        n_code = sum(1 for c in reloaded["cells"] if c["cell_type"] == "code")
        gpu = reloaded["metadata"]["kaggle"]["accelerator"] == "gpu"
        internet = reloaded["metadata"]["kaggle"]["isInternetEnabled"]
        summary.append({
            "file": fname,
            "cells": n_cells,
            "markdown": n_md,
            "code": n_code,
            "gpu": gpu,
            "internet": internet,
            "valid_json": True,
        })
    print("=" * 60)
    print(f"Built {len(summary)} notebooks in: {base}")
    print("=" * 60)
    for s in summary:
        print(f"  {s['file']:30s}  cells={s['cells']:>2}  (md={s['markdown']}, code={s['code']})  gpu={s['gpu']}  internet={s['internet']}")
    print("=" * 60)


if __name__ == "__main__":
    main()

def md(*lines):
    """Create a markdown cell. Lines are joined with newlines."""
    src = []
    for i, ln in enumerate(lines):
        if i < len(lines) - 1:
            src.append(ln + "\n")
        else:
            src.append(ln)
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": src,
    }


def code(*lines):
    """Create a code cell with null execution_count and empty outputs."""
    src = []
    for i, ln in enumerate(lines):
        if i < len(lines) - 1:
            src.append(ln + "\n")
        else:
            src.append(ln)
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": src,
    }


def notebook(cells):
    return {
        "nbformat": 4,
        "nbformat_minor": 4,
        "metadata": {
            "kernelspec": KERNELSPEC,
            "language_info": LANGUAGE_INFO,
            "kaggle": KAGGLE_META,
        },
        "cells": list(cells),
    }



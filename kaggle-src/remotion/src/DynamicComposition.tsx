import React, { useMemo } from 'react';
import {
  AbsoluteFill,
  OffthreadVideo,
  useCurrentFrame,
  useVideoConfig,
  interpolate,
  Img,
} from 'remotion';
import type { DynamicCompositionProps } from './types';
import { HormoziCaption } from './compositions/HormoziCaption';
import { InfoCard } from './compositions/InfoCard';
import { ProgressBar } from './compositions/ProgressBar';
import { DentalBroll } from './compositions/DentalBroll';
import { BrandLogo } from './components/BrandLogo';
import { Icon } from './components/Icon';
import { MICKY_THEME, FONTS, PROGRESS_BAR_HEIGHT } from './theme';

/**
 * DynamicComposition — the main montage composition generated by the Python
 * pipeline (kaggle-src/montage/remotion_renderer.py).
 *
 * Renders the background video, then overlays:
 *   1. Hormozi-style captions (word-by-word)
 *   2. Info cards at key moments
 *   3. Dental B-roll animations
 *   4. Bottom progress bar
 *   5. Brand watermark
 */
export const DynamicComposition: React.FC<DynamicCompositionProps> = ({
  videoPath,
  captions,
  infoCards = [],
  broll = [],
  chapters = [],
  options = {},
}) => {
  const frame = useCurrentFrame();
  const { fps, durationInFrames } = useVideoConfig();
  const {
    showCaptions = true,
    showProgressBar = true,
    showInfoCards = true,
    showBroll = true,
    showWatermark = true,
    showEndCard = false,
    rtl = true,
    brandColor = MICKY_THEME.brandBlue,
    captionColor = MICKY_THEME.captionYellow,
    logoPath,
    socialHandles = {},
  } = options;

  // ---- Active caption group (the one whose phrase is on-screen) ----
  const activeCaptionGroup = useMemo(() => {
    const nowSec = frame / fps;
    return captions.find((group) => {
      const start = group.words[0]?.start ?? 0;
      const end = group.words[group.words.length - 1]?.end ?? 0;
      return nowSec >= start && nowSec <= end + 0.2;
    });
  }, [frame, fps, captions]);

  // ---- End-card (last 5 seconds) ----
  const endCardFrameStart = durationInFrames - 5 * fps;
  const showEndCardNow =
    showEndCard && frame >= endCardFrameStart && frame < durationInFrames;
  const endCardOpacity = interpolate(
    frame,
    [endCardFrameStart, endCardFrameStart + 15, durationInFrames - 10, durationInFrames],
    [0, 1, 1, 0],
    { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' }
  );

  // ---- Watermark opacity (fades in for the first 30 frames) ----
  const watermarkOpacity = interpolate(frame, [0, 30], [0, 0.85], {
    extrapolateRight: 'clamp',
  });

  return (
    <AbsoluteFill style={{ backgroundColor: MICKY_THEME.black }}>
      {/* ---------- Background video ---------- */}
      <AbsoluteFill>
        <OffthreadVideo src={videoPath} muted style={{ width: '100%', height: '100%', objectFit: 'cover' }} />
      </AbsoluteFill>

      {/* ---------- Captions ---------- */}
      {showCaptions && activeCaptionGroup && (
        <AbsoluteFill
          style={{
            justifyContent: 'flex-end',
            alignItems: 'center',
            paddingBottom: `${PROGRESS_BAR_HEIGHT + 80}px`,
            pointerEvents: 'none',
          }}
        >
          <HormoziCaption
            words={activeCaptionGroup.words}
            rtl={rtl}
            fontSize={90}
            highlightColor={captionColor}
          />
        </AbsoluteFill>
      )}

      {/* ---------- Info cards ---------- */}
      {showInfoCards &&
        infoCards.map((card) => {
          const startFrame = Math.round(card.start * fps);
          const durationFrames = Math.round((card.duration ?? 5) * fps);
          if (frame < startFrame || frame > startFrame + durationFrames + 15) {
            return null;
          }
          return <InfoCard key={card.id} card={card} position="right" />;
        })}

      {/* ---------- Dental B-roll ---------- */}
      {showBroll &&
        broll.map((b) => {
          const startFrame = Math.round(b.start * fps);
          const durationFrames = Math.round((b.duration ?? 3) * fps);
          if (frame < startFrame || frame > startFrame + durationFrames + 15) {
            return null;
          }
          return <DentalBroll key={b.id} broll={b} />;
        })}

      {/* ---------- Watermark ---------- */}
      {showWatermark && (
        <AbsoluteFill style={{ pointerEvents: 'none', padding: '32px', opacity: watermarkOpacity }}>
          <div
            style={{
              position: 'absolute',
              top: 32,
              left: rtl ? undefined : 32,
              right: rtl ? 32 : undefined,
              display: 'flex',
              alignItems: 'center',
              gap: 12,
              fontFamily: FONTS.cairoBold,
              fontSize: 28,
              color: MICKY_THEME.white,
              textShadow: `0 2px 8px ${MICKY_THEME.black}`,
              direction: rtl ? 'rtl' : 'ltr',
            }}
          >
            {logoPath ? (
              <Img src={logoPath} style={{ width: 44, height: 44, borderRadius: 22 }} />
            ) : (
              <Icon name="Tooth" size={36} color={brandColor} animation="none" />
            )}
            <span>د. ميكي</span>
          </div>
        </AbsoluteFill>
      )}

      {/* ---------- Progress bar ---------- */}
      {showProgressBar && (
        <AbsoluteFill style={{ justifyContent: 'flex-end', pointerEvents: 'none' }}>
          <ProgressBar color={brandColor} height={PROGRESS_BAR_HEIGHT} chapters={chapters} />
        </AbsoluteFill>
      )}

      {/* ---------- End card ---------- */}
      {showEndCardNow && (
        <AbsoluteFill
          style={{
            backgroundColor: MICKY_THEME.black,
            opacity: endCardOpacity,
            justifyContent: 'center',
            alignItems: 'center',
            flexDirection: 'column',
            gap: 32,
            fontFamily: FONTS.cairoBold,
            color: MICKY_THEME.white,
          }}
        >
          <Icon name="Tooth" size={120} color={brandColor} animation="bounce" durationInFrames={30} />
          <div style={{ fontSize: 64, fontWeight: 800 }}>تابعني على</div>
          <div style={{ display: 'flex', gap: 40, flexDirection: 'row' }}>
            {socialHandles.instagram && <BrandLogo platform="instagram" size={80} animation="pop" />}
            {socialHandles.tiktok && <BrandLogo platform="tiktok" size={80} animation="pop" delayInFrames={5} />}
            {socialHandles.youtube && <BrandLogo platform="youtube" size={80} animation="pop" delayInFrames={10} />}
            {socialHandles.whatsapp && <BrandLogo platform="whatsapp" size={80} animation="pop" delayInFrames={15} />}
            {socialHandles.facebook && <BrandLogo platform="facebook" size={80} animation="pop" delayInFrames={20} />}
          </div>
        </AbsoluteFill>
      )}
    </AbsoluteFill>
  );
};
